'use strict';
const { test, expect, setupOwner, adminAction, state, action, goTo, today } = require('./ux-fixture.cjs');

test('연속 입고는 날짜와 메모를 유지하고 실패한 다음 품목의 입력을 지킨다', async ({ page }) => {
  await setupOwner(page);
  await action(page, 'inventory.item', { name: '검수 샴푸', kind: '판매 상품', unit: '개', min: 2, price: 10000, active: true });
  let snapshot = await action(page, 'inventory.item', { name: '검수 트리트먼트', kind: '판매 상품', unit: '개', min: 2, price: 15000, active: true });
  const [shampoo, treatment] = ['검수 샴푸', '검수 트리트먼트'].map(name => snapshot.data.items.find(item => item.name === name));
  await page.reload();
  await goTo(page, '재고 · 입고');
  await page.getByRole('button', { name: '+ 수동 입고', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '수동 입고', exact: true });
  await dialog.getByLabel('입고 품목 검색', { exact: true }).fill('샴푸');
  await expect(dialog.getByLabel('입고 품목', { exact: true }).locator('option')).toHaveCount(2);
  await dialog.getByLabel('입고 품목', { exact: true }).selectOption(shampoo.id);
  await dialog.getByLabel('추가할 수량 (개)', { exact: true }).fill('3');
  await dialog.getByLabel('메모 (선택)', { exact: true }).fill('공급업체 거래명세표 10-05');
  await dialog.getByRole('button', { name: '입고 저장 후 다음 품목', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('검수 샴푸 3개 입고를 저장');
  await expect(dialog.getByLabel('입고 품목', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('추가할 수량', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('입고일', { exact: true })).toHaveValue(today());
  await expect(dialog.getByLabel('메모 (선택)', { exact: true })).toHaveValue('공급업체 거래명세표 10-05');
  await expect(dialog.getByLabel('입고 품목 검색', { exact: true })).toBeFocused();
  await dialog.getByLabel('입고 품목 검색', { exact: true }).fill('트리트먼트');
  await dialog.getByLabel('입고 품목', { exact: true }).selectOption(treatment.id);
  await dialog.getByLabel('추가할 수량 (개)', { exact: true }).fill('5');
  await page.route('**/api/actions/inventory.receipt', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'TEST_UNAVAILABLE', message: '입고 저장을 다시 시도해 주세요.' } }) }), { times: 1 });
  await dialog.getByRole('button', { name: '입고 저장', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('입고 저장을 다시 시도');
  await expect(dialog.getByLabel('입고 품목', { exact: true })).toHaveValue(treatment.id);
  await expect(dialog.getByLabel('추가할 수량 (개)', { exact: true })).toHaveValue('5');
  expect((await state(page)).data.receipts).toHaveLength(1);
  await dialog.getByRole('button', { name: '입고 저장', exact: true }).click();
  await expect(dialog).toBeHidden();
  snapshot = await state(page);
  expect(snapshot.data.receipts).toHaveLength(2);
  expect(snapshot.data.items.find(item => item.id === shampoo.id).qty).toBe(3);
  expect(snapshot.data.items.find(item => item.id === treatment.id).qty).toBe(5);
  expect(snapshot.data.receipts.every(receipt => receipt.memo === '공급업체 거래명세표 10-05')).toBeTruthy();
});

test('수납에서 연락처와 시술을 검색해 선택하고 모바일에서도 기록한다', async ({ page }) => {
  await setupOwner(page);
  let snapshot = await action(page, 'customer.save', { name: '검색 고객', phone: '010-9876-5432', memo: '', warning: '' });
  const customer = snapshot.data.customers[0];
  await action(page, 'customer.save', { name: '다른 고객', phone: '010-1111-2222', memo: '', warning: '' });
  await adminAction(page, 'service.save', { name: '남성 커트', price: 15000, duration: 30, materials: [], active: true });
  snapshot = await adminAction(page, 'service.save', { name: '프리미엄 염색', price: 70000, duration: 60, materials: [], active: true });
  const service = snapshot.data.services.find(row => row.name === '프리미엄 염색');
  const staff = snapshot.data.staff[0];
  await page.reload();
  await goTo(page, '수납 · 환불');
  await page.getByRole('button', { name: '+ 수납 기록', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '새 수납 기록', exact: true });
  await dialog.getByLabel('고객 빠른 검색', { exact: true }).fill('0109876');
  await expect(dialog.getByLabel('고객', { exact: true }).locator('option')).toHaveCount(2);
  await dialog.getByLabel('고객', { exact: true }).selectOption(customer.id);
  await dialog.getByLabel('담당 직원', { exact: true }).selectOption(staff.id);
  await dialog.getByRole('combobox', { name: '시술이나 상품 담기', exact: true }).fill('염색');
  await expect(dialog.getByRole('option')).toHaveCount(1);
  await dialog.getByRole('option', { name: /프리미엄 염색/ }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy();
  await dialog.getByRole('checkbox', { name: /단말기 승인/ }).check();
  await dialog.getByRole('button', { name: '수납 70,000원 기록', exact: true }).click();
  await expect(dialog).toBeHidden();
  snapshot = await state(page);
  expect(snapshot.data.transactions).toHaveLength(1);
  expect(snapshot.data.transactions[0].customerId).toBe(customer.id);
  expect(snapshot.data.transactions[0].total).toBe(70000);
  await page.getByLabel('검색', { exact: true }).fill('01098765432');
  await expect(page.getByText('조회 결과 1건', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '검색 고객 결제 상세', exact: true })).toBeVisible();
});

test('정산 검색은 관리 영역 안에서 유지하고 업무 화면으로 나가면 민감한 조건을 지운다', async ({ page }) => {
  await setupOwner(page);
  let snapshot = await adminAction(page, 'service.save', { name: '정산 커트', price: 10000, duration: 30, materials: [], active: true });
  const staff = snapshot.data.staff[0];
  const service = snapshot.data.services[0];
  snapshot = await action(page, 'payment.create', { guestName: '대조 고객', staffId: staff.id, lines: [{ type: 'service', refId: service.id, quantity: 2 }], discount: 0, method: 'card', reference: 'CARD-APPROVAL-A', notes: '' });
  const transaction = snapshot.data.transactions[0];
  await action(page, 'payment.refund', { transactionId: transaction.id, lines: [{ lineId: transaction.lines[0].id, quantity: 1, restock: false }], method: 'card', reference: 'REFUND-A', reason: '시술 한 건 환불' });
  await action(page, 'payment.create', { guestName: '다른 고객', staffId: staff.id, lines: [{ type: 'service', refId: service.id, quantity: 1, unitPrice: 5000 }], discount: 0, method: 'cash', reference: '', notes: '' });
  await page.reload();
  await goTo(page, '매출 · 정산');
  await page.getByLabel('정산 거래 검색', { exact: true }).fill('CARD-APPROVAL-A');
  const summary = page.locator('.commerce-result-summary');
  await expect(summary).toContainText('검색 결과 2건');
  await expect(summary).toContainText('결제 20,000원');
  await expect(summary).toContainText('환불 10,000원');
  await expect(summary).toContainText('순수납 10,000원');
  await page.getByLabel('거래 유형', { exact: true }).selectOption('refund');
  await expect(summary).toContainText('검색 결과 1건');
  await expect(summary).toContainText('순수납 -10,000원');
  await goTo(page, '직원 관리');
  await goTo(page, '매출 · 정산');
  await expect(page.getByLabel('정산 거래 검색', { exact: true })).toHaveValue('CARD-APPROVAL-A');
  await expect(page.getByLabel('거래 유형', { exact: true })).toHaveValue('refund');
  await page.getByRole('button', { name: '상세', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '수납 상세', exact: true });
  await expect(dialog).toContainText('대조 고객');
  await dialog.getByRole('button', { name: '닫기', exact: true }).first().click();
  await goTo(page, '매출 · 정산');
  await expect(page.getByLabel('정산 거래 검색', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('거래 유형', { exact: true })).toHaveValue('all');
  await expect(summary).toContainText('검색 결과 3건');
  await expect(summary).toContainText('순수납 15,000원');
});
